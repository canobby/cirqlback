// retro-font — a bundled 3×5 bitmap font for the Main Street Arcade cabinets.
//
// No external font (CSP-safe): each glyph is five 3-wide rows of "#"/" ". The
// RetroEngine blits these into its pixel buffer at any integer scale, so the same
// tiny font gives crisp score readouts and big pixel titles alike. Uppercase only
// (lowercase folds to uppercase); digits, and the handful of symbols the games use.

const G = (...rows: string[]) => rows; // 5 rows, 3 cols each

